const SEEN_KEY = 'kojoHouse.updSeen';
const latest = () => (UPDATES[0] && UPDATES[0].d) || '';
// まだ見ていない新しいアップデートがあるか（一度も開いていない人も「ある」）
export function hasNewUpdates() {
  try { return (localStorage.getItem(SEEN_KEY) || '') < latest(); } catch (e) { return false; }
}
function markSeen() { try { localStorage.setItem(SEEN_KEY, latest()); } catch (e) { } }

const dateText = d => { const [, m, dd] = d.split('-'); return +m + '月' + +dd + '日'; };

export function openUpdates(onClose) {
  const body = h('div', { cls: 'upd' });
  UPDATES.forEach(u => body.appendChild(h('section', { cls: 'upd-day' }, [
    h('h4', { text: dateText(u.d) }),
    h('ul', null, u.items.map(t => h('li', { text: t }))),
  ])));
  markSeen();
  modal('アップデート情報', body, [h('button', { cls: 'btn', text: 'とじる', onclick: () => { closeModal(); if (onClose) onClose(); } })], 'upd-dlg');
}
